declare(strict_types=1);

namespace kim\present\libcontainer\logic;

/** How a menu slot reacts to a player's interaction. */
enum SlotMode{
    /** Nothing can be taken from or put into the slot. */
    case LOCKED;
    /** Items can be moved freely (subject to validators and change handlers). */
    case FREE;
    /** The slot is a button: the click is cancelled and its callback is invoked. */
    case BUTTON;
}
